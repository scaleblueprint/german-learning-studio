/* Static visual-content guard: avoid showing unrelated photographs as vocabulary objects. */
import fs from 'node:fs';import assert from 'node:assert/strict';
const ext=fs.readFileSync('dist/a11-visual-extensions.js','utf8');
const studio=fs.readFileSync('dist/a11-photo-studio.js','utf8');
const page=fs.readFileSync('dist/index.html','utf8');
assert.match(ext,/photoByExactTerm/);
assert.match(ext,/creditForTerm/);
assert.match(ext,/onerror="this.hidden=true;this.nextElementSibling.hidden=false"/);
assert.match(ext,/const photoByExactTerm=\{\};/);
assert.ok(ext.includes('objectPhotos'), 'Preserve specifically matched, credited object photos');
assert.ok(!ext.includes("'die U-Bahn':1"),'Never display a tram as U-Bahn');
assert.ok(page.includes('a11-visual-extensions.js'));
assert.ok(page.includes('a11-photo-studio.js'));
assert.ok(studio.includes('data-route-feedback'));
assert.ok(studio.includes('data-clock-words'));
assert.ok(studio.includes("Bahnhof:'geradeaus',Park:'nach rechts',Rathaus:'zurück',Hotel:'nach links'"));
assert.ok(studio.includes("a===b?'':"));
const storyboards=fs.readFileSync('dist/a11-storyboards.js','utf8');
for(let n=1;n<=6;n++)assert.ok(storyboards.includes(n+':{title:'),'Missing chapter storyboard '+n);
assert.ok(storyboards.includes('data-sb-next'));
const app=fs.readFileSync('dist/app.js','utf8');
const workbook=fs.readFileSync('dist/photo-practice.js','utf8');
assert.ok(!app.includes('realPhotos(ch.number,{compact:true,heading:false})'),'Duplicate chapter carousel');
assert.ok(!app.includes('realPhotos(unit.number,{compact:true,heading:false})'),'Duplicate workbook carousel');
assert.ok(!app.includes('realPhotos(l.chapterNumber)'),'Duplicate lesson carousel');
assert.ok(!storyboards.includes('photoMarkup=photo?'),'Storyboards must not repeat a chapter photo');
assert.ok(!workbook.includes('esc(p.src)'), 'Workbook must use independent scene illustrations');
console.log('Visual content mapping, no-repeat-photo guard and component wiring checks passed.');
